import assert from 'node:assert/strict';
import OpenAI, {APIUserAbortError as OpenAIAbortError} from 'openai';
import Anthropic, {APIUserAbortError as AnthropicAbortError} from '@anthropic-ai/sdk';
import {GoogleGenAI} from '@google/genai';

const url = process.env.FAKEAPI_TEST_URL;
const key = process.env.FAKEAPI_CLIENT_KEY;
const model = 'fakeapi-test';
const openai = new OpenAI({apiKey:key, baseURL:url+'/v1', maxRetries:0});
const messages = [{role:'user',content:'只回答 OK'}];
assert.equal((await openai.models.list()).data.length,2);
assert.equal((await openai.models.retrieve(model)).id,model);
assert.equal((await openai.chat.completions.create({model,messages})).choices[0].message.content,'OK');
let text='';
for await (const e of await openai.chat.completions.create({model,messages,stream:true,stream_options:{include_usage:true}})) {
  if(e.choices[0]) text+=e.choices[0].delta.content??'';
}
assert.equal(text,'OK');
const response=await openai.responses.create({model,input:'只回答 OK',store:false});
assert.equal(response.output_text,'OK');
const stream=openai.responses.stream({model,input:'只回答 OK',store:false});
text='';
for await(const e of stream) if(e.type==='response.output_text.delta') text+=e.delta;
assert.equal(text,'OK');
assert.equal((await stream.finalResponse()).output_text,'OK');
assert.equal((await openai.responses.create({model,store:false,input:[{role:'user',content:'old'},...response.output,{role:'user',content:'只回答 OK'}]})).output_text,'OK');
const schema={type:'object',properties:{ok:{type:'boolean'},source:{type:'string'}},required:['ok','source'],additionalProperties:false};
const structured=await openai.responses.create({model,input:'/test/json',store:false,text:{format:{type:'json_schema',name:'fixture',schema,strict:true}}});
assert.deepEqual(JSON.parse(structured.output_text),{ok:true,source:'fakeapi'});
console.log('PASS OpenAI Node: Chat, Responses, final helper, JSON, models');
const tools=[{type:'function',name:'get_weather',parameters:{type:'object',properties:{city:{type:'string'}},required:['city'],additionalProperties:false}}];
const toolStream=openai.responses.stream({model,input:'/test/tool',tools,tool_choice:'required',store:false});
const first=await toolStream.finalResponse();
const call=first.output[0];
assert.equal(call.name,'get_weather');
const final=await openai.responses.create({model,store:false,input:[{role:'user',content:'/test/tool'},call,{type:'function_call_output',call_id:call.call_id,output:'25 C'}]});
assert.equal(final.output_text,'工具测试完成。');
const anthropic=new Anthropic({apiKey:key,baseURL:url+'/anthropic',maxRetries:0});
assert.equal((await anthropic.models.list()).data.length,2);
assert.equal((await anthropic.models.retrieve(model)).id,model);
const result=await anthropic.messages.create({model,max_tokens:128,messages});
assert.equal(result.content[0].text,'OK');
const as=anthropic.messages.stream({model,max_tokens:128,messages});
assert.equal((await as.finalMessage()).content[0].text,'OK');
console.log('PASS Anthropic Node: create, stream, final helper, models');
const weather=[{name:'get_weather',input_schema:{type:'object',properties:{city:{type:'string'}},required:['city']}}];
const toolMessage=await anthropic.messages.stream({model,max_tokens:128,messages:[{role:'user',content:'/test/tool'}],tools:weather,tool_choice:{type:'any'}}).finalMessage();
const acall=toolMessage.content[0];
assert.deepEqual(acall.input,{city:'Guangzhou'});
const afinal=await anthropic.messages.create({model,max_tokens:128,messages:[{role:'user',content:'/test/tool'},{role:'assistant',content:[acall]},{role:'user',content:[{type:'tool_result',tool_use_id:acall.id,content:'25 C'}]}]});
assert.equal(afinal.content[0].text,'工具测试完成。');
const ajson=await anthropic.messages.create({model,max_tokens:128,messages:[{role:'user',content:'/test/json'}],output_config:{format:{type:'json_schema',schema}}});
assert.deepEqual(JSON.parse(ajson.content[0].text),{ok:true,source:'fakeapi'});
const google=new GoogleGenAI({apiKey:key,httpOptions:{baseUrl:url,apiVersion:'v1beta'}});
assert.equal((await google.models.get({model})).name,'models/'+model);
const catalog=await google.models.list();
const listed=[];
for await(const item of catalog) listed.push(item);
assert.equal(listed.length,2);
assert.equal((await google.models.generateContent({model,contents:'只回答 OK'})).text,'OK');
text='';
for await(const event of await google.models.generateContentStream({model,contents:'只回答 OK'})) text+=event.text??'';
assert.equal(text,'OK');
const json=await google.models.generateContent({model,contents:'/test/json',config:{responseMimeType:'application/json',responseJsonSchema:schema}});
assert.deepEqual(JSON.parse(json.text),{ok:true,source:'fakeapi'});
console.log('PASS Google Node: generate, stream, JSON');
const gtools=[{functionDeclarations:[{name:'get_weather',parameters:{type:'OBJECT',properties:{city:{type:'STRING'}},required:['city']}}]}];
const gfirst=await google.models.generateContent({model,contents:'/test/tool',config:{tools:gtools,toolConfig:{functionCallingConfig:{mode:'ANY'}}}});
const gcall=gfirst.candidates[0].content.parts[0].functionCall;
assert.deepEqual(gcall.args,{city:'Guangzhou'});
const glast=await google.models.generateContent({model,contents:[{role:'user',parts:[{text:'/test/tool'}]},{role:'model',parts:[{functionCall:gcall}]},{role:'user',parts:[{functionResponse:{name:gcall.name,response:{temperature:25}}}]}]});
assert.equal(glast.text,'工具测试完成。');
console.log('PASS Node SDK single-tool round trips');
await assert.rejects(openai.responses.create({model,input:'hello',store:true}),e=>e.status===400);
await assert.rejects(anthropic.messages.create({model,max_tokens:0,messages}),e=>e.status===400);
await assert.rejects(google.models.generateContent({model:'unknown-model',contents:'hello'}),e=>e.status===404);
const slowMessages=[{role:'user',content:'SDK cancellation exercise'}];
const canceledChat=await openai.chat.completions.create({model:'fakeapi-frog',messages:slowMessages,stream:true});
for await(const event of canceledChat) { canceledChat.controller.abort(); break; }
const canceledResponse=openai.responses.stream({model:'fakeapi-frog',input:'SDK cancellation exercise',store:false});
for await(const event of canceledResponse) { canceledResponse.abort(); break; }
await assert.rejects(canceledResponse.finalResponse(),e=>e instanceof OpenAIAbortError);
const canceledAnthropic=anthropic.messages.stream({model:'fakeapi-frog',messages:slowMessages,max_tokens:8192});
for await(const event of canceledAnthropic) { canceledAnthropic.abort(); break; }
await assert.rejects(canceledAnthropic.finalMessage(),e=>e instanceof AnthropicAbortError);
const controller=new AbortController();
const canceledGoogle=await google.models.generateContentStream({model:'fakeapi-frog',contents:'SDK cancellation exercise',config:{abortSignal:controller.signal}});
for await(const event of canceledGoogle) { controller.abort(); break; }
assert.equal(controller.signal.aborted,true);
console.log('PASS Node SDK errors and explicit aborts');
